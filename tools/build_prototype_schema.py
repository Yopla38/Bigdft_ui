#!/usr/bin/env python3
"""Join the extracted BigDFT schema with the UI curation and emit the compact
catalogue loaded by the prototype (``prototype/js/schema.js``).

Fails loudly when the curation references a variable that no longer exists
upstream, so a BigDFT upgrade cannot silently orphan a control.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent


def main() -> int:
    schema = json.loads((ROOT / "schema/bigdft-input.schema.json").read_text())
    tiers = yaml.safe_load((ROOT / "schema/ui-tiers.yaml").read_text())

    variables = {}
    for namespace, entry in schema["namespaces"].items():
        for section in entry["sections"]:
            for var in section["variables"]:
                variables[f"{namespace}.{section['name']}.{var['name']}"] = (namespace, section["name"], var)

    listed = set(tiers["essential"]) | set(tiers["advanced"]) | {p for ps in tiers["overrides"].values() for p in ps}
    if missing := sorted(listed - variables.keys()):
        print("ui-tiers.yaml references unknown variables:\n  " + "\n  ".join(missing), file=sys.stderr)
        return 1
    if both := sorted(set(tiers["essential"]) & set(tiers["advanced"])):
        print("listed as both essential and advanced:\n  " + "\n  ".join(both), file=sys.stderr)
        return 1

    override = {path: brique for brique, paths in tiers["overrides"].items() for path in paths}
    catalogue = []
    for path, (namespace, section, var) in variables.items():
        item = {
            "p": path if namespace != "bigdft" else path.removeprefix("bigdft."),
            "b": override.get(path, tiers["sections"][f"{namespace}.{section}"]),
            "t": 0 if path in tiers["essential"] else 1 if path in tiers["advanced"] else 2,
            "d": var["default"],
            "c": var["comment"],
        }
        if "range" in var:
            item["r"] = var["range"]
        if "enum" in var:
            item["e"] = [e["value"] for e in var["enum"]]
        if "condition" in var and var["condition"].get("master_key"):
            item["if"] = var["condition"]["master_key"]
        catalogue.append(item)

    out = ROOT / "prototype/js/schema.js"
    out.parent.mkdir(parents=True, exist_ok=True)
    payload = {"revision": schema["source_revision"], "variables": catalogue}
    out.write_text(
        "// Generated by tools/build_prototype_schema.py from the BigDFT source - do not edit.\n"
        "window.OND = window.OND || {};\n"
        f"OND.schema = {json.dumps(payload, ensure_ascii=False, separators=(',', ':'), default=str)};\n"
    )
    counts = [sum(1 for v in catalogue if v["t"] == t) for t in (0, 1, 2)]
    print(f"{out.relative_to(ROOT)}: {len(catalogue)} variables (essential {counts[0]}, advanced {counts[1]}, expert {counts[2]})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
