#!/usr/bin/env python3
"""Bundle the registry of study steps for the workshop (workshop/js/steps.js).

    python tools/build_steps.py

Reads for_pybigdft_pack/study/StudyActions.py the way an interface should: by
introspection. Each public function is a step; its signature gives the fields
of its box, its docstring the words, the module docstring the families. A
pre-filled step is one that only calls `calculation` with settings: it is
called here on a recording study to learn what it fills in.

Nothing about a step is written in the workshop: add a function to the
registry, run this, and the box exists.
"""
from __future__ import annotations

import importlib.util
import inspect
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REGISTRY = ROOT / "for_pybigdft_pack/study/StudyActions.py"
LINKS = ("after", "wavefunctions", "of", "relative_to", "among", "a", "b", "against")


class Recorder:
    """Stands for a study: remembers what a step function asks to add."""

    def __init__(self):
        self.added = []

    def add(self, kind, name, **what):
        self.added.append(dict(kind=kind, name=name, **what))
        return "step"


def main() -> int:
    spec = importlib.util.spec_from_file_location("StudyActions", REGISTRY)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)

    family = {}
    for title, body in re.findall(r"\n([^\n]+)\n-{5,}\n\n\.\. autosummary::\n\n((?:   \w+\n?)+)", module.__doc__):
        for name in body.split():
            family[name] = title.strip()

    steps = []
    for name, func in vars(module).items():
        if name.startswith("_") or not inspect.isfunction(func):
            continue
        doc = inspect.getdoc(func) or ""
        head, _, rest = doc.partition("\n\n")
        words = rest.split("Args:")[0].strip()
        helps = dict(re.findall(r"^\s{3}(\w+)(?: \([^)]*\))?: (.+(?:\n\s{6,}.+)*)", doc, re.M))
        params = []
        for p in list(inspect.signature(func).parameters.values())[2:]:          # after (study, name)
            if p.kind in (p.VAR_KEYWORD, p.VAR_POSITIONAL):
                continue
            params.append({"name": p.name, "link": p.name in LINKS, "required": p.default is p.empty,
                           "default": None if p.default is p.empty else (list(p.default) if isinstance(p.default, tuple) else p.default),
                           "help": " ".join(helps.get(p.name, "").split())})
        entry = {"name": name, "family": family.get(name, ""), "summary": " ".join(head.split()), "words": " ".join(words.split()),
                 "params": params}
        # a pre-filled step: what does it add, called with its defaults?
        recorder = Recorder()
        try:
            func(recorder, "probe", **{p["name"]: "step" for p in params if p["link"] and p["required"]})
            added = recorder.added[0]
            entry["kind"] = added["kind"]
            if name not in (added["kind"],):
                entry["fills"] = {"actions": added.get("actions") or {}, "keys": added.get("keys") or {}}
        except Exception as error:      # a step that needs more than links to be called: it is its own kind
            entry["kind"] = name
            entry["note"] = str(error)
        steps.append(entry)

    out = ROOT / "workshop/js/steps.js"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("// Generated by tools/build_steps.py from for_pybigdft_pack/study/StudyActions.py - do not edit.\n"
                   "window.OND = window.OND || {};\n"
                   f"OND.steps = {json.dumps(steps, ensure_ascii=False, separators=(',', ':'))};\n")
    print(f"{out.relative_to(ROOT)}: {len(steps)} steps | " + ", ".join(f"{s['name']} ({s['kind']}{', pre-filled' if 'fills' in s else ''})" for s in steps))
    return 0


if __name__ == "__main__":
    sys.exit(main())
