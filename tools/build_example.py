#!/usr/bin/env python3
"""Bundle the example study that was really run, for the study builder.

``examples/water-study`` holds a study written by the builder of the prototype
(``blocks.json`` is its board, ``attempt-N/study.py`` the script it generated)
and executed with the BigDFT 1.9.1 image the PyBigDFT pack pins: every input
dry-run by the script itself, then computed with the one command a HAPS runs,
``bigdft -n NAME``. Two attempts are kept, because the first one teaches
something: with the default convergence criterion the triplet runs stop on
different electronic states.

This tool reads the logs and writes ``prototype/js/example.js``.

    python tools/build_example.py
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_results import HA_EV, relaxation, single_point  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "examples/water-study"
IMAGE = "bigdft/runtime@sha256:6f16f65f5b33ffe83e53d3c228c21a1e8eb97d0b426f4fad0c805d0bc0540336"
ATTEMPTS = [("attempt-1", "First attempt: default criterion, 10⁻⁴"), ("attempt-2", "Second attempt: criterion 10⁻⁵")]


def tidy(warning) -> str:
    """A warning as one readable line (YAML reads some of them as mappings)."""
    text = re.sub(r"[{}'\"]", "", str(warning)).replace("XC is XC: ", "XC is ")
    return re.sub(r"\s+", " ", text).strip()


def walltime(text: str) -> float | None:
    """Total wall time of a run, from the last line BigDFT writes about it."""
    found = re.findall(r"Walltime since initialization\s*:\s*(\d+):(\d+):([\d.]+)", text)
    return round(int(found[-1][0]) * 3600 + int(found[-1][1]) * 60 + float(found[-1][2]), 2) if found else None


def attempt(directory: Path, label: str) -> dict:
    script = (directory / "study.py").read_text()
    body = script.split("    inp = Inputfile()\n", 1)[1].split("    return inp", 1)[0]
    runs, relax = {}, {}
    for log in sorted((directory / "runs").glob("log-*.yaml")):
        name = log.stem[len("log-"):]
        item = single_point(log)
        keep = ("xc", "nspin", "h", "gnrm_cv", "energy", "iters", "gnrm", "converged", "warnings", "wall", "mem", "nc", "nf", "dof", "version")
        runs[name] = {k: item[k] for k in keep}
        runs[name]["warnings"] = [tidy(w) for w in item["warnings"]]
        if "orbitals" in item:
            runs[name]["homo"] = [item["orbitals"]["up"][-1]] + ([item["orbitals"]["down"][-1]] if item["orbitals"]["down"] else [])
        rel = relaxation(log)
        if rel and len(rel["steps"]) > 1:
            # BigDFT's own word on the optimiser, not a test of ours on the last force
            said = re.search(r"Iterations when SQNM converged\s*:\s*(\d+)", log.read_text())
            relax[name] = {k: rel[k] for k in ("method", "forcemax", "steps", "energy", "fmax")}
            relax[name].update(converged=bool(said), iterations=int(said.group(1)) if said else None, evaluations=len(rel["steps"]))
            runs[name].update(energy=rel["energy"], wall=walltime(log.read_text()), evaluations=len(rel["steps"]))
    energies = {n: (relax[n]["energy"] if n in relax else r["energy"]) for n, r in runs.items()}
    gaps = {n[2:]: (energies[n] - energies["A" + n[1:]]) * HA_EV for n in energies if n.startswith("B_")}
    return {"id": directory.name, "label": label, "script": script, "base": [line.strip() for line in body.splitlines() if line.strip()],
            "runs": runs, "relax": relax, "gaps": gaps}


def main() -> int:
    refused = (SOURCE / "attempt-1/refused/bigdft-err-PBE0-without-pseudopotential.yaml").read_text()
    reason = " ".join(line.strip() for line in refused.splitlines()[5:8])
    reason = reason.split(" Calling sequence")[0].strip()
    example = {
        "system": "Water", "image": IMAGE, "blocks": json.loads((SOURCE / "blocks.json").read_text()),
        "attempts": [attempt(SOURCE / name, label) for name, label in ATTEMPTS], "refused": reason,
    }
    out = ROOT / "prototype/js/example.js"
    out.write_text(
        "// Generated by tools/build_example.py from examples/water-study (real BigDFT 1.9.1 runs) - do not edit.\n"
        "window.OND = window.OND || {};\n"
        f"OND.example = {json.dumps(example, ensure_ascii=False, separators=(',', ':'))};\n"
    )
    for a in example["attempts"]:
        print(a["id"], {k: round(v, 3) for k, v in a["gaps"].items()}, "| relaxation", {n: (r["evaluations"], r["converged"], r["fmax"]) for n, r in a["relax"].items()})
    print(f"{out.relative_to(ROOT)}: {out.stat().st_size // 1024} kB | refused: {reason}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
