#!/usr/bin/env python3
"""Check config/haps.yaml and bundle it for the mock-up (prototype/js/targets.js).

The file lists the HAPS a calculation can be sent to. This tool refuses an
entry that lacks an address or a limit, or that writes a secret instead of
naming the environment variable that holds it.

    python tools/build_targets.py
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
REQUIRED = ("label", "detail", "ebservice_url", "ebuffer_url", "mcp_url", "application", "credentials", "bigdft", "gpu", "limits", "accepts", "estimate")
LIMITS = ("max_timeout_s", "max_parallel", "output_reserve_mb", "buffer_lifespan_s")


def problems(config: dict) -> list[str]:
    out, haps = [], config.get("haps") or {}
    if config.get("default") not in haps:
        out.append(f"default: {config.get('default')!r} is not one of {sorted(haps)}")
    for key, h in haps.items():
        out += [f"{key}: {field} is missing" for field in REQUIRED if field not in h]
        out += [f"{key}: {field} is not an http(s) address" for field in ("ebservice_url", "ebuffer_url", "mcp_url")
                if not re.match(r"^https?://[^\s/]+", str(h.get(field, "")))]
        out += [f"{key}: limits.{field} must be a positive integer" for field in LIMITS
                if not (isinstance((h.get("limits") or {}).get(field), int) and h["limits"][field] > 0)]
        out += [f"{key}: credentials.{field} must name an environment variable, not hold a value"
                for field, value in (h.get("credentials") or {}).items() if not re.match(r"^[A-Z][A-Z0-9_]*$", str(value))]
        if not isinstance((h.get("accepts") or {}).get("wavefunctions"), bool):
            out.append(f"{key}: accepts.wavefunctions must be true or false")
    return out


def main() -> int:
    config = yaml.safe_load((ROOT / "config/haps.yaml").read_text())
    bad = problems(config)
    if bad:
        print("config/haps.yaml:\n  " + "\n  ".join(bad), file=sys.stderr)
        return 1
    out = ROOT / "prototype/js/targets.js"
    out.write_text(
        "// Generated by tools/build_targets.py from config/haps.yaml - do not edit.\n"
        "window.OND = window.OND || {};\n"
        f"OND.targets = {json.dumps(config, ensure_ascii=False, separators=(',', ':'))};\n"
    )
    print(f"{out.relative_to(ROOT)}: " + ", ".join(f"{k}{' (example)' if h.get('example') else ''}" for k, h in config["haps"].items()))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
