#!/usr/bin/env python3
"""Bundle PyBigDFT's registry of input actions for the workshop.

    python tools/build_actions.py [for_pybigdft_pack/build/<version>]

PyBigDFT keeps its input actions in one module, BigDFT.InputActions: every
public function there becomes a method of every Inputfile. That module is the
registry. `for_pybigdft_pack/extract/extract.py` reads it in the pack's image
(signatures, defaults, docstrings, the categories its own documentation gives)
and calls each action to see what it writes and which argument drives which
key. This tool turns that record into prototype/js/actions.js, from which the
workshop draws one control per action. Nothing about an action is written by
hand here: a new version of PyBigDFT changes the list, not this file.

It also checks the PyBigDFT calls the workshop writes itself (prototype/js/
blueprint.js and builder.js): a call to an action, or an input key, the installed
version does not have stops the build (exit status 3).
"""
from __future__ import annotations

import ast
import json
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
#: Where an action goes when it writes nothing a block owns: by the category PyBigDFT gives it.
BY_CATEGORY = {"Basic Setup": "theory", "Self-Consistent": "accuracy", "Input-Output": "observables",
               "Post-Processing": "observables", "Setting atomic": "matter"}


def literal(text):
    try:
        return ast.literal_eval(text)
    except Exception:
        return None


def kind(value) -> str:
    if isinstance(value, bool):
        return "bool"
    if isinstance(value, (int, float)):
        return "number"
    if isinstance(value, str):
        return "text"
    if isinstance(value, list):
        return "list"
    return "other"


def main() -> int:
    builds = sorted((ROOT / "for_pybigdft_pack/build").glob("pybigdft-*"))
    build = (Path(sys.argv[1]) if len(sys.argv) > 1 else builds[-1]).resolve()
    actions = json.loads((build / "actions.json").read_text())
    versions = json.loads((build / "versions.json").read_text())
    schema = json.loads((ROOT / "prototype/js/schema.js").read_text().split("OND.schema = ", 1)[1].rstrip().rstrip(";"))
    block_of = {v["p"]: v["b"] for v in schema["variables"]}

    out = []
    for a in actions:
        writes = a["writes"] or {}
        blocks = Counter(block_of[p] for p in writes if p in block_of)
        block = blocks.most_common(1)[0][0] if blocks else next(
            (b for prefix, b in BY_CATEGORY.items() if a.get("category", "").startswith(prefix)), "theory")
        params = []
        for p in a["parameters"]:
            default = literal(p["default"]) if p["default"] is not None else None
            params.append({"name": p["name"], "kind": kind(default) if p["default"] is not None else "required",
                           "default": default, "shown": p["default"]})
        maps = {}
        for name, probe in (a.get("arguments") or {}).items():
            if "keys" in probe:
                maps[name] = {"when": probe["when"], "keys": [{k: v for k, v in key.items() if k != "removed" or v} for key in probe["keys"]]}
        out.append({"name": a["name"], "category": a.get("category", ""), "summary": a["summary"], "doc": a["doc"],
                    "params": params, "writes": writes if a["writes"] is not None else None, "maps": maps,
                    "block": block, "method": a["is_method"], "note": a["error"] or ""})

    names = {a["name"] for a in out}
    unknown = []
    for source in ("prototype/js/blueprint.js", "prototype/js/builder.js", "prototype/js/steps.js"):
        for called in sorted(set(re.findall(r"\binp\.(\w+)\(", (ROOT / source).read_text()))):
            if called not in names and called not in ("update", "setdefault", "get"):
                unknown.append(f"{source}: inp.{called}() is not an input action of PyBigDFT {versions['pybigdft']}")
    # ... and the input keys it writes itself: each must be a variable of this version
    blueprint = (ROOT / "prototype/js/blueprint.js").read_text()
    written = set(re.findall(r"\bput\('([\w.]+)',\s*'(\w+)'", blueprint))
    written |= {tuple(path.rsplit(".", 1)) for path in re.findall(r"\w+: \[[^\]]*?, '([a-z_]+(?:\.\w+)+)', '\w+'\]", blueprint)}
    for section, key in sorted(written):
        if f"{section}.{key}" not in block_of:
            unknown.append(f"prototype/js/blueprint.js writes {section}.{key}, which is not an input variable of BigDFT {versions['bigdft']}")
    if unknown:
        print("The workshop writes things this version does not have:\n  " + "\n  ".join(unknown), file=sys.stderr)
        return 3

    stamp = f"PyBigDFT {versions['pybigdft']}, BigDFT {versions['bigdft']}"
    target = ROOT / "prototype/js/actions.js"
    target.write_text(
        f"// Generated by tools/build_actions.py from {build.relative_to(ROOT)} - do not edit.\n"
        "window.OND = window.OND || {};\n"
        f"OND.actions = {json.dumps({'version': stamp, 'list': out}, ensure_ascii=False, separators=(',', ':'))};\n")
    per_block = Counter(a["block"] for a in out)
    print(f"{target.relative_to(ROOT)}: {len(out)} actions of {stamp} | " + ", ".join(f"{b} {n}" for b, n in sorted(per_block.items()))
          + f" | {sum(1 for a in out if a['writes'] is None)} not callable here | checked: {len(written)} keys and the PyBigDFT calls the workshop writes itself")
    return 0


if __name__ == "__main__":
    sys.exit(main())
