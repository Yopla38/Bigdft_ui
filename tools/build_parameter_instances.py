#!/usr/bin/env python3
"""Generate the instantiated parameter graph and the description corpus.

Two outputs, for the two ways a pack memory is filled:

``ontology/instances/bigdft-parameters.ttl``
    Exact facts about every input variable (section, block, tier, default,
    bounds, allowed values, activation condition) and every profile, under
    ``ontology/workshop_layer.ttl``. Meant for pack-kit's ``ttl_instances``
    loader: no LLM reads it, so no value can be paraphrased.

``ontology/corpus/bigdft-variables.md``
    One Markdown section per variable carrying the prose DESCRIPTION of the
    source. Meant for a ``sources.yaml`` entry with the ``markdown_sections``
    preprocess: one memory per variable, cut at the headings.

Regenerate both after a BigDFT upgrade.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
TIERS = ("essential", "advanced", "expert")
PREFIX = "ws"


def literal(text: str) -> str:
    """A Turtle string literal with the escapes Turtle requires."""
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "\\r") + '"'


def local(kind: str, name: str) -> str:
    """A safe local name: letters, digits and underscores only."""
    return f"{PREFIX}:{kind}_" + re.sub(r"[^A-Za-z0-9]", "_", name)


def is_number(value) -> bool:
    return isinstance(value, (int, float)) and not isinstance(value, bool) and value == value and abs(value) != float("inf")


def main() -> int:
    schema = json.loads((ROOT / "schema/bigdft-input.schema.json").read_text())
    tiers = yaml.safe_load((ROOT / "schema/ui-tiers.yaml").read_text())
    override = {p: b for b, ps in tiers["overrides"].items() for p in ps}
    layer = (ROOT / "ontology/workshop_layer.ttl").read_text()
    namespace = re.search(r"@prefix ws:\s+<([^>]+)>", layer).group(1)

    ttl = [
        "# Generated by tools/build_parameter_instances.py from the BigDFT source - do not edit.",
        f"# Source revision: {schema['source_revision']}",
        f"@prefix {PREFIX}: <{namespace}> .",
        "@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .",
        "@prefix xsd: <http://www.w3.org/2001/XMLSchema#> .",
        "",
    ]
    for key, block in tiers["blocks"].items():
        ttl.append(f"{local('Block', key)} a {PREFIX}:Block ; rdfs:label {literal(block['label'])}@en ; rdfs:comment {literal(block['role'])}@en .")
    for tier in TIERS:
        ttl.append(f"{local('Tier', tier)} a {PREFIX}:Tier ; rdfs:label {literal(tier)}@en .")
    ttl.append("")

    corpus = ["# BigDFT input variables", "", f"Source: bigdft-suite, revision {schema['source_revision']}.", ""]
    known, count = {}, 0
    for ns, entry in schema["namespaces"].items():
        for section in entry["sections"]:
            for var in section["variables"]:
                known[f"{ns}.{section['name']}.{var['name']}"] = var
    for ns, entry in schema["namespaces"].items():
        for section in entry["sections"]:
            sec_path = f"{ns}.{section['name']}".removeprefix("bigdft.")
            ttl.append(f"{local('Section', sec_path)} a {PREFIX}:Section ; rdfs:label {literal(sec_path)} .")
            for var in section["variables"]:
                full = f"{ns}.{section['name']}.{var['name']}"
                path = full.removeprefix("bigdft.")
                block = override.get(full, tiers["sections"][f"{ns}.{section['name']}"])
                tier = TIERS[0 if full in tiers["essential"] else 1 if full in tiers["advanced"] else 2]
                facts = [
                    f"a {PREFIX}:Parameter",
                    f"rdfs:label {literal(path)}",
                    f"{PREFIX}:inputPath {literal(path)}",
                    f"{PREFIX}:inSection {local('Section', sec_path)}",
                    f"{PREFIX}:exposedIn {local('Block', block)}",
                    f"{PREFIX}:hasTier {local('Tier', tier)}",
                    f"{PREFIX}:defaultValue {literal(json.dumps(var['default'], ensure_ascii=False))}",
                ]
                if var["comment"]:
                    facts.append(f"{PREFIX}:shortDescription {literal(var['comment'])}@en")
                bounds = var.get("range")
                if bounds and is_number(bounds[0]):
                    facts.append(f"{PREFIX}:lowerBound {literal(repr(float(bounds[0])))}^^xsd:double")
                if bounds and len(bounds) > 1 and is_number(bounds[1]):
                    facts.append(f"{PREFIX}:upperBound {literal(repr(float(bounds[1])))}^^xsd:double")
                if "enum" in var:
                    facts.append(f"{PREFIX}:allowedValues {literal(json.dumps([e['value'] for e in var['enum']], ensure_ascii=False))}")
                master = (var.get("condition") or {}).get("master_key")
                if master and f"{ns}.{section['name']}.{master}" in known:
                    facts.append(f"{PREFIX}:dependsOn {local('Parameter', f'{sec_path}.{master}')}")
                ttl.append(f"{local('Parameter', path)} " + " ;\n  ".join(facts) + " .")

                corpus += [f"## {path}", ""]
                corpus.append(f"`{var['name']}` is an input variable of section `{sec_path}` ({entry['source']}). "
                              f"The workshop exposes it in the {tiers['blocks'][block]['label']} block, at the {tier} tier.")
                if var["comment"]:
                    corpus.append(f"Purpose: {var['comment']}.")
                corpus.append(f"Default: `{json.dumps(var['default'], ensure_ascii=False)}`.")
                if "description" in var:
                    corpus += ["", var["description"]]
                corpus.append("")
                count += 1
            ttl.append("")
        for name, profile in entry.get("import_profiles", {}).items():
            facts = [f"a {PREFIX}:Profile", f"rdfs:label {literal(name)}",
                     f"{PREFIX}:profileValues {literal(json.dumps(profile['overrides'], ensure_ascii=False))}"]
            if profile["comment"]:
                facts.append(f"rdfs:comment {literal(profile['comment'])}@en")
            for sec, values in profile["overrides"].items():
                if isinstance(values, dict):
                    for key, value in values.items():
                        for candidate in (f"{ns}.{sec}.{key}", *(f"{ns}.{sec}.{key}.{sub}" for sub in (value if isinstance(value, dict) else {}))):
                            if candidate in known:
                                facts.append(f"{PREFIX}:sets {local('Parameter', candidate.removeprefix('bigdft.'))}")
            ttl.append(f"{local('Profile', f'{ns}_{name}')} " + " ;\n  ".join(dict.fromkeys(facts)) + " .")
            corpus += [f"## Profile {name}", "",
                       f"`{name}` is a profile called with `import: {name}`. {profile['comment']}. {profile['description']}".strip(), ""]
        ttl.append("")

    (ROOT / "ontology/instances").mkdir(parents=True, exist_ok=True)
    (ROOT / "ontology/corpus").mkdir(parents=True, exist_ok=True)
    (ROOT / "ontology/instances/bigdft-parameters.ttl").write_text("\n".join(ttl))
    (ROOT / "ontology/corpus/bigdft-variables.md").write_text("\n".join(corpus))
    print(f"ontology/instances/bigdft-parameters.ttl and ontology/corpus/bigdft-variables.md: {count} variables")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
