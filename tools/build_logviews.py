#!/usr/bin/env python3
"""Bundle PyBigDFT's registry of log attributes for the workshop (workshop/js/logviews.js).

    python tools/build_logviews.py [for_pybigdft_pack/build/<version>]

PyBigDFT reads a log through one table, BigDFT.Logfiles.BUILTIN: each entry
names an attribute of a Logfile (log.energy, log.forces, log.evals ...) and the
paths in the YAML document where its value may be. That table is the registry
of what a calculation gives. `for_pybigdft_pack/extract/extract.py` records it
in the pack's image; this tool turns the record into the list the workshop
draws its result views from. A new version of PyBigDFT changes the list, not
the workshop: an attribute it does not know yet is shown by the shape of its
value.

`attribute_values()` reads those attributes from a log the way Logfile does:
the first path that exists, the highest occupied level worked out from the
levels when the log does not print it, and the two memory tables kept under
`log.memory`. tools/build_library.py uses it, so that what the workshop shows
for a run is what PyBigDFT gives. This was compared with PyBigDFT 0.9 in the
pack's image, attribute by attribute, on the logs of examples/water-ionisation.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def latest_build() -> Path:
    builds = sorted(p for p in (ROOT / "for_pybigdft_pack/build").iterdir() if (p / "api.json").is_file())
    return builds[-1]


def attributes(build: Path) -> list[dict]:
    """The registry: name, label PyBigDFT prints it with, paths, whether it is read once for the whole log."""
    out = []
    for a in json.loads((build / "api.json").read_text())["attributes"]:
        paths = [[int(key) if re.fullmatch(r"-?\d+", key) else key for key in path.split(" > ")] for path in a["paths"]]
        entry = {"name": a["name"], "label": a["label"] if isinstance(a["label"], str) else None, "paths": paths, "global": bool(a["input"])}
        if a["name"] in IN_MEMORY:          # Logfile moves these two under log.memory, by the title they have in the log
            entry["access"] = 'log.memory["%s"]' % paths[0][0]
        out.append(entry)
    return out


IN_MEMORY = ("memory_run", "memory_quantities")


def fermi_level(evals):
    """Logfile._fermi_level_from_evals: the last occupied level of the list."""
    level = reference = None
    for index, ev in enumerate(evals):
        if ev.get("e") is not None:
            reference = ev["f"] if index == 0 else reference
            level = ev["e"]
            if ev["f"] < 0.5 * reference:
                break
        occupied = ev.get("e_occ", ev.get("e_occupied"))
        if occupied is not None:
            level = max(occupied) if isinstance(occupied, list) else occupied
        if ev.get("e_vrt", ev.get("e_virt")) is not None:
            break
    return level


def follow(doc, path):
    value = doc
    for key in path:
        try:
            value = value[key]
        except (KeyError, TypeError, IndexError):
            return None
    return value


def attribute_values(documents: list[dict], registry: list[dict]) -> dict:
    """What each attribute gives for a log. Of a log of several documents (a relaxation), the results
    are those of the last document, as `log[len(log) - 1]` gives them; what describes the run is in the first."""
    out = {}
    for a in registry:
        for doc in ([documents[0], documents[-1]] if a["global"] else [documents[-1]]):
            value = next((v for v in (follow(doc, path) for path in a["paths"]) if v is not None), None)
            if value is not None:
                out[a["name"]] = value
                break
    if "fermi_level" not in out and isinstance(out.get("evals"), list):
        level = fermi_level(out["evals"])
        if level is not None:
            out["fermi_level"] = level
    return out


def main() -> int:
    build = (Path(sys.argv[1]) if len(sys.argv) > 1 else latest_build()).resolve()
    registry = attributes(build)
    versions = json.loads((build / "versions.json").read_text())
    out = ROOT / "workshop/js/logviews.js"
    body = {"version": f"PyBigDFT {versions['pybigdft']}, BigDFT {versions['bigdft']}", "attributes": registry}
    out.write_text("// Generated by tools/build_logviews.py from BigDFT.Logfiles.BUILTIN - do not edit.\n"
                   "window.OND = window.OND || {};\n"
                   f"OND.logviews = {json.dumps(body, ensure_ascii=False, separators=(',', ':'))};\n")
    print(f"{out.relative_to(ROOT)}: {len(registry)} log attributes of {body['version']} | "
          f"{sum(a['global'] for a in registry)} describe the run, {sum(not a['global'] for a in registry)} are results")
    return 0


if __name__ == "__main__":
    sys.exit(main())
