#!/usr/bin/env python3
"""Bundle the guided-path notebooks for the prototype.

``guides/manifest.yaml`` lists the notebooks an administrator has published,
with the few things a notebook does not say about itself (level, duration, a
one-line summary). This tool strips each notebook down to the text of its
cells (no outputs, no execution counts, no metadata) and writes
``prototype/js/guides.js``. The steps themselves are derived in the browser by
``prototype/js/notebook.js``, the same importer that reads a notebook an
administrator adds from the Library, so there is one reading of a notebook.

    python tools/build_guides.py
    python tools/build_guides.py --strip path/to/notebook.ipynb   # print a stripped copy
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
LEVELS = ("Discovery", "Intermediate", "Advanced")


def strip(path: Path) -> dict:
    """Keep only what a guided path needs: cell types and their source text."""
    notebook = json.loads(path.read_text())
    if notebook.get("nbformat", 4) < 4 or "cells" not in notebook:
        raise SystemExit(f"{path}: not an nbformat 4 notebook")
    cells = []
    for cell in notebook["cells"]:
        if cell.get("cell_type") not in ("markdown", "code"):
            continue
        source = cell.get("source", "")
        source = "".join(source) if isinstance(source, list) else source
        if source.strip():
            cells.append({"cell_type": cell["cell_type"], "source": source})
    return {"nbformat": 4, "nbformat_minor": 5, "metadata": {}, "cells": cells}


def main() -> int:
    if len(sys.argv) == 3 and sys.argv[1] == "--strip":
        print(json.dumps(strip(Path(sys.argv[2])), indent=1, ensure_ascii=False))
        return 0
    manifest = yaml.safe_load((ROOT / "guides/manifest.yaml").read_text())
    bundle = []
    for entry in manifest["guides"]:
        if entry["level"] not in LEVELS:
            raise SystemExit(f"{entry['file']}: level must be one of {', '.join(LEVELS)}")
        bundle.append({
            "id": Path(entry["file"]).stem,
            "level": entry["level"],
            "minutes": int(entry["minutes"]),
            "summary": entry["summary"],
            "origin": manifest["origin"],
            "notebook": strip(ROOT / "guides/notebooks" / entry["file"]),
        })
    out = ROOT / "prototype/js/guides.js"
    out.write_text(
        "// Generated by tools/build_guides.py from guides/ - do not edit.\n"
        "window.OND = window.OND || {};\n"
        f"OND.guides = {json.dumps(bundle, ensure_ascii=False, separators=(',', ':'))};\n"
    )
    print(f"{out.relative_to(ROOT)}: {len(bundle)} notebooks, {out.stat().st_size // 1024} kB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
